const TWAP_DESC: &str = "This market will resolve to \"Up\" if the time-weighted average price (TWAP) of Bitcoin, generated by Chainlink, of the time range specified in the title is greater than or equal to the price at the beginning of that range. Otherwise, it will resolve to \"Down\".\nThe resolution source for this market is information from Chainlink, specifically the BTC/USD TWAP data stream available at https://data.chain.link/streams/btc-usd-twap-60s-streams.";

async fn pool() -> PgPool {
    let url = std::env::var("TEST_DATABASE_URL")
        .expect("TEST_DATABASE_URL must point at a disposable PostgreSQL database");
    let pool = polygemy_engine::db::connect(&url, 5).await.unwrap();
    polygemy_engine::db::migrate(&pool).await.unwrap();
    pool
}

fn cid() -> String {
    format!(
        "0x{}{}",
        uuid::Uuid::new_v4().simple(),
        uuid::Uuid::new_v4().simple()
    )
}

fn token() -> String {
    uuid::Uuid::new_v4().as_u128().to_string()
}

struct Mkt {
    cid: String,
    up: String,
    down: String,
    start_us: i64,
    end_us: i64,
    desc: &'static str,
    accepting: bool,
    winner: Option<&'static str>,
}

impl Mkt {
    fn new(start_us: i64) -> Self {
        Mkt {
            cid: cid(),
            up: token(),
            down: token(),
            start_us,
            end_us: start_us + 300_000_000,
            desc: TWAP_DESC,
            accepting: true,
            winner: None,
        }
    }

    fn gamma(&self) -> Value {
        let iso = |us| to_datetime(us).to_rfc3339();
        json!({"id": "1", "conditionId": self.cid, "slug": format!("m-{}", &self.cid[2..10]), "question": "Bitcoin Up or Down",
            "description": self.desc, "eventStartTime": iso(self.start_us), "endDate": iso(self.end_us),
            "outcomes": "[\"Up\", \"Down\"]", "clobTokenIds": format!("[\"{}\", \"{}\"]", self.up, self.down),
            "closed": false, "acceptingOrders": self.accepting, "enableOrderBook": true, "orderPriceMinTickSize": 0.01, "orderMinSize": 5, "negRisk": false})
    }

    fn clob_details(&self) -> Value {
        json!({"c": self.cid, "t": [{"t": self.up, "o": "Up"}, {"t": self.down, "o": "Down"}], "mts": 0.01, "mos": 5, "ao": self.accepting, "fd": {"r": 0.07, "e": 1, "to": true}})
    }

    fn clob_market(&self) -> Value {
        json!({"condition_id": self.cid, "tokens": [
            {"token_id": self.up, "outcome": "Up", "winner": self.winner == Some("Up")},
            {"token_id": self.down, "outcome": "Down", "winner": self.winner == Some("Down")}]})
    }
}

/// Minimal HTTP/1.1 server: path prefix -> JSON body; everything else 404.
async fn mock_server(routes: Arc<Mutex<HashMap<String, Value>>>) -> String {
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    tokio::spawn(async move {
        loop {
            let (mut sock, _) = listener.accept().await.unwrap();
            let routes = routes.clone();
            tokio::spawn(async move {
                let mut buf = vec![0u8; 8192];
                let n = sock.read(&mut buf).await.unwrap_or(0);
                let req = String::from_utf8_lossy(&buf[..n]);
                let path = req.split_whitespace().nth(1).unwrap_or("/").to_string();
                let body = routes
                    .lock()
                    .unwrap()
                    .iter()
                    .find(|(k, _)| path.starts_with(k.as_str()))
                    .map(|(_, v)| v.to_string());
                let resp = match body {
                    Some(b) => format!("HTTP/1.1 200 OK\r\ncontent-type: application/json\r\ncontent-length: {}\r\nconnection: close\r\n\r\n{b}", b.len()),
                    None => "HTTP/1.1 404 Not Found\r\ncontent-length: 0\r\nconnection: close\r\n\r\n".to_string(),
                };
                let _ = sock.write_all(resp.as_bytes()).await;
            });
        }
    });
    format!("http://{addr}")
}

async fn state_of(pool: &PgPool, cid: &str) -> Option<String> {
    sqlx::query_scalar("SELECT state FROM market_lifecycles WHERE condition_id = $1")
        .bind(cid)
        .fetch_optional(pool)
        .await
        .unwrap()
}

async fn wait_state(pool: &PgPool, cid: &str, want: &str) {
    let ok = tokio::time::timeout(Duration::from_secs(20), async {
        loop {
            if state_of(pool, cid).await.as_deref() == Some(want) {
                return;
            }
            tokio::time::sleep(Duration::from_millis(100)).await;
        }
    })
    .await;
    assert!(
        ok.is_ok(),
        "{cid} never reached {want}; is {:?}",
        state_of(pool, cid).await
    );
}

/// Waits for a subscribe frame naming `token` (other markets may subscribe in the same tick).
async fn wait_subscribe(rx: &mut mpsc::UnboundedReceiver<String>, token: &str) {
    let found = tokio::time::timeout(Duration::from_secs(5), async {
        while let Some(f) = rx.recv().await {
            if f.contains(token) && f.contains("\"subscribe\"") {
                return;
            }
        }
    })
    .await;
    assert!(found.is_ok(), "no subscribe frame for {token}");
}

fn manager(pool: &PgPool, url: &str, poly: PolyHandle, required: Arc<FeedHealth>) -> Manager {
    Manager::new(
        pool.clone(),
        Discovery::new(
            reqwest::Client::new(),
            url.to_string(),
            url.to_string(),
            "btc-up-or-down-5m".into(),
        ),
        ManagerConfig {
            window_secs: 300,
            preload_lead: Duration::from_secs(60),
            entry_cutoff: Duration::from_secs(30),
            discovery_interval: Duration::from_secs(1),
            lookahead: Duration::from_secs(600),
            settlement_poll: Duration::from_secs(1),
            reference_tolerance: Duration::from_secs(5),
        },
        format!("test-{}", uuid::Uuid::new_v4().simple()),
        "local",
        poly,
        vec![required],
        Arc::new(FeedHealth::new("discovery", false, Duration::from_secs(5))),
    )
}

#[tokio::test]
async fn lifecycle_end_to_end_with_restart() {
    let pool = pool().await;
    let now = now_us();
    let active = Mkt::new(now - 10_000_000); // window open now
    let mut ended = Mkt::new(now - 400_000_000); // window already over, resolved Up
    ended.winner = Some("Up");
    let duplicate = Mkt::new(active.start_us); // second listing for the same window
    let mut bad_rules = Mkt::new(now + 20_000_000);
    bad_rules.desc = "Resolves Up if Binance BTCUSDT closes higher.";
    let mut halted = Mkt::new(now - 20_000_000);
    halted.accepting = false; // stopped accepting orders mid-window
    halted.start_us += 1_000_000; // distinct window from `active`
    halted.end_us += 1_000_000;

    // Chainlink TWAP references at the ended market's boundaries: 100 -> 101 => Up.
    for (ts, v) in [(ended.start_us, "100.5"), (ended.end_us, "101.25")] {
        sqlx::query("INSERT INTO chainlink_reports (feed, provider, observed_ts, value, window_seconds, received_ts, from_snapshot, quality) VALUES ('btcusd_twap60', 'chainlink', $1, $2::numeric, 60, now(), false, 'valid') ON CONFLICT DO NOTHING")
            .bind(to_datetime(ts))
            .bind(v)
            .execute(&pool)
            .await
            .unwrap();
    }

    let all = [&active, &ended, &duplicate, &bad_rules, &halted];
    let mut routes = HashMap::new();
    routes.insert(
        "/series".to_string(),
        json!([{"id": "77", "slug": "btc-up-or-down-5m"}]),
    );
    routes.insert("/events/keyset".to_string(), json!({"events": [{"id": "e1", "markets": all.iter().map(|m| m.gamma()).collect::<Vec<_>>()}]}));
    for m in all {
        routes.insert(format!("/clob-markets/{}", m.cid), m.clob_details());
        routes.insert(format!("/markets/{}", m.cid), m.clob_market());
    }
    let url = mock_server(Arc::new(Mutex::new(routes))).await;

    // Required feed (stands in for Chainlink TWAP) is healthy.
    let required = Arc::new(FeedHealth::new(
        "chainlink_twap60",
        true,
        Duration::from_secs(60),
    ));
    required.on_connected();
    required.on_message(now_us(), None, now_us(), true);

    // A real Polymarket session shares state with the manager; we feed it the books.
    let state = Arc::new(PolyState::default());
    let (cmd_tx, mut cmd_rx) = mpsc::unbounded_channel();
    let (sink, _rx) = persist::channel(1000);
    let mut session = Polymarket::new(
        Ctx::new(
            sink,
            Arc::new(FeedHealth::new("polymarket", true, Duration::from_secs(5))),
            true,
        ),
        "ws://unused".into(),
        state.clone(),
    );

    let (stop_tx, stop_rx) = watch::channel(false);
    let task = tokio::spawn(
        manager(
            &pool,
            &url,
            PolyHandle::new(state.clone(), cmd_tx.clone()),
            required.clone(),
        )
        .run(stop_rx),
    );

    // Preload subscribes the active market's tokens; READY needs both books.
    wait_state(&pool, &active.cid, "PRELOADING").await;
    wait_subscribe(&mut cmd_rx, &active.up).await;
    tokio::time::sleep(Duration::from_millis(1500)).await;
    assert_eq!(
        state_of(&pool, &active.cid).await.as_deref(),
        Some("PRELOADING"),
        "not READY without books"
    );
    for t in [&active.up, &active.down] {
        let book = json!({"event_type": "book", "market": active.cid, "asset_id": t, "timestamp": "1", "bids": [{"price": "0.48", "size": "10"}], "asks": [{"price": "0.52", "size": "10"}]});
        session
            .on_text(&book.to_string(), Received::now(), &mut vec![])
            .unwrap();
    }
    wait_state(&pool, &active.cid, "ACTIVE").await;

    // Ended market: validated after its window -> settles with official result and our references.
    wait_state(&pool, &ended.cid, "COMPLETED").await;
    let (computed, official, start_ref): (Option<String>, Option<String>, Option<rust_decimal::Decimal>) =
        sqlx::query_as("SELECT computed_outcome, official_outcome, start_reference FROM market_lifecycles WHERE condition_id = $1").bind(&ended.cid).fetch_one(&pool).await.unwrap();
    assert_eq!(
        (computed.as_deref(), official.as_deref()),
        (Some("Up"), Some("Up"))
    );
    assert_eq!(start_ref.unwrap().to_string(), "100.50000000");

    wait_state(&pool, &duplicate.cid, "INVALID").await;
    wait_state(&pool, &bad_rules.cid, "INVALID").await;
    let errs: Value =
        sqlx::query_scalar("SELECT validation_errors FROM markets WHERE condition_id = $1")
            .bind(&bad_rules.cid)
            .fetch_one(&pool)
            .await
            .unwrap();
    assert!(errs.to_string().contains("methodology"), "{errs}");
    // Halted market never trades: it is waiting for settlement, with the reason recorded.
    wait_state(&pool, &halted.cid, "SETTLEMENT_PENDING").await;
    let reason: String = sqlx::query_scalar("SELECT reason FROM market_lifecycle_events WHERE condition_id = $1 AND to_state = 'MARKET_ENDED'").bind(&halted.cid).fetch_one(&pool).await.unwrap();
    assert!(reason.contains("closed before"), "{reason}");

    let tokens: i64 =
        sqlx::query_scalar("SELECT count(*) FROM market_tokens WHERE condition_id = $1")
            .bind(&active.cid)
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(tokens, 2);

    // ---- Restart: a new manager resumes from PostgreSQL, keeps ACTIVE and re-subscribes.
    stop_tx.send(true).unwrap();
    task.await.unwrap();
    let events_before: i64 =
        sqlx::query_scalar("SELECT count(*) FROM market_lifecycle_events WHERE condition_id = $1")
            .bind(&active.cid)
            .fetch_one(&pool)
            .await
            .unwrap();
    while cmd_rx.try_recv().is_ok() {}
    let state2 = Arc::new(PolyState::default());
    let (stop_tx, stop_rx) = watch::channel(false);
    let task =
        tokio::spawn(manager(&pool, &url, PolyHandle::new(state2, cmd_tx), required).run(stop_rx));
    wait_subscribe(&mut cmd_rx, &active.up).await; // restored after restart
    tokio::time::sleep(Duration::from_millis(2500)).await;
    assert_eq!(
        state_of(&pool, &active.cid).await.as_deref(),
        Some("ACTIVE")
    );
    let events_after: i64 =
        sqlx::query_scalar("SELECT count(*) FROM market_lifecycle_events WHERE condition_id = $1")
            .bind(&active.cid)
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(
        events_before, events_after,
        "no lifecycle replay after restart"
    );
    stop_tx.send(true).unwrap();
    task.await.unwrap();
}

#[tokio::test]
async fn transitions_are_guarded_in_the_database() {
    let pool = pool().await;
    let m = Mkt::new(now_us());
    sqlx::query("INSERT INTO markets (condition_id, validation_status) VALUES ($1, 'pending')")
        .bind(&m.cid)
        .execute(&pool)
        .await
        .unwrap();
    assert_eq!(
        repo::ensure_lifecycle(&pool, &m.cid, "a").await.unwrap(),
        State::Discovered
    );
    assert_eq!(
        repo::ensure_lifecycle(&pool, &m.cid, "b").await.unwrap(),
        State::Discovered,
        "idempotent"
    );

    // Illegal edge refused before touching the database.
    assert!(
        repo::transition(&pool, &m.cid, State::Discovered, State::Active, "x", "a")
            .await
            .is_err()
    );
    repo::transition(
        &pool,
        &m.cid,
        State::Discovered,
        State::Validating,
        "ok",
        "a",
    )
    .await
    .unwrap();
    // A second process acting on stale state loses the compare-and-set.
    let e = repo::transition(
        &pool,
        &m.cid,
        State::Discovered,
        State::Validating,
        "stale",
        "b",
    )
    .await
    .unwrap_err();
    assert!(e.to_string().contains("another process"));

    repo::transition(&pool, &m.cid, State::Validating, State::Invalid, "bad", "a")
        .await
        .unwrap();
    // Even a raw UPDATE cannot revive a terminal market.
    let r = sqlx::query("UPDATE market_lifecycles SET state = 'ACTIVE' WHERE condition_id = $1")
        .bind(&m.cid)
        .execute(&pool)
        .await;
    assert!(r.unwrap_err().to_string().contains("final"));
}
